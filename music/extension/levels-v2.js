/** 与 level.js 的 groundAt 同算法，供各章独立求高度。 */
export function makeGroundAt(terrain, fallback = WORLD_V2.ground) {
  return function groundAt(x) {
    for (let i = 1; i < terrain.length; i++) {
      if (x < terrain[i][0]) {
        const [ax, ay] = terrain[i - 1], [bx, by] = terrain[i];
        return ay + (by - ay) * Math.max(0, (x - ax) / (bx - ax));
      }
    }
    return fallback;
  };
}

/** 障碍 ID 使用稳定前缀，便于存档与测试引用。 */
export function buildObstacles(prefix, layout) {
  return layout.map(([type, x, width, height], index) => ({
    id: `${prefix}-hazard-${index}`, type, x, width, height: height || 0,
  }));
}

/** 与 hazardBounds 同规则；weave / shroud / step 等新类型由模拟层单独判定。 */
export function hazardBoundsFor(o, groundAt) {
  const ground = groundAt(o.x);
  if (o.type === 'block') return { left: o.x + 5, right: o.x + o.width - 5, top: ground - o.height + 5, bottom: ground };
  if (o.type === 'beam') return { left: o.x + 6, right: o.x + o.width - 6, top: ground - 200, bottom: ground - 43 };
  return null;
}

